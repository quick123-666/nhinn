const CHANNELS = ['太阳', '阳明', '少阳', '太阴', '少阴', '厥阴']

// 主标签: meridian 字段取第一个单经（"太阳/太阴"→太阳；"太阴/肺"→太阴）
function primaryChannel(meridian: string): string | null {
  const m = simplify(meridian)
  for (const c of CHANNELS) if (m.startsWith(c)) return c
  return null
}

type Sample = {id: number, src: string, title: string, features: number[], labelName: string, via: string}

function extractFeatures(...texts: string[]): number[] {
  const joined = simplify(texts.join(' '))
  return DIMS.map(d => {
    let n = 0
    for (const w of d.words) {
      let i = 0
      while ((i = joined.indexOf(w, i)) !== -1) { n++; i += w.length }
    }
    return Math.min(100, n * 40)
  })
}

const formulas = JSON.parse(readFileSync('formulas.json', 'utf8'))
const samples: Sample[] = []
let id = 0
let drop = 0, multi = 0

for (const f of (formulas.formulas ?? [])) {
  const name = f.name ?? ''
  const meridian = f.meridian ?? ''
  if (!meridian || meridian.includes('外用')) { drop++; continue }
  const label = primaryChannel(meridian)
  if (!label) { drop++; continue }
  const isMulti = meridian.includes('/')
  if (isMulti) multi++
  const keywords = Array.isArray(f.keywords) ? f.keywords.join(' ') : ''
  const features = extractFeatures(f.indication ?? '', keywords, f.explanation ?? '', name)
  if (features.every(x => x === 0)) { drop++; continue }
  samples.push({id: id++, src: 'formula', title: name, features, labelName: label, via: isMulti ? 'meridian复合取主' : 'meridian字段'})
}

