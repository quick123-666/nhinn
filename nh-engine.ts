export function simplify(t: string): string {
  let s = t
  for (const [tr, si] of SIMPLE_MAP) s = s.split(tr).join(si)
  return s
}

export interface Weights {
  weights: number[], thresholds: number[], dims: string[], channels: string[], trained: string
}
export function loadWeights(path = 'nh-weights.json'): Weights {
  return JSON.parse(readFileSync(path, 'utf8')) as Weights
}

// 症状文本 → 21 维特征（每维命中词数×40，上限100）
export function featsFromText(text: string): {feats: number[], hits: string[]} {
  const joined = simplify(text)
  const feats: number[] = []
  const hits: string[] = []
  for (const d of Object.keys(DICT)) {
    let n = 0
    for (const w of DICT[d] ?? []) {
      let i = 0
      while ((i = joined.indexOf(w, i)) !== -1) { n++; i += w.length }
    }
    feats.push(Math.min(100, n * 40))
    if (n > 0) hits.push(d)
  }
  return {feats, hits}
}

// 词级提取：返回文本中命中的具体症状词（去重），供医案相似度/直证用
export function extractMatchedWords(text: string): string[] {
  const joined = simplify(text)
  const found: string[] = []
  for (const d of Object.keys(DICT)) {
    for (const w of DICT[d] ?? []) {
      if (joined.includes(w)) found.push(w)
    }
  }
  return [...new Set(found)]
}

// 21 维特征 + 权重 → 六经评分/概率/最佳
export function predict(feats: number[], W: Weights): {scores: number[], probs: number[], best: number, bestName: string} {
  const scaled = feats.map(x => x / 50)
  const scores = W.channels.map((_, k) => {
    let s = -W.thresholds[k]!
    for (let j = 0; j < W.dims.length; j++) s += W.weights[k * W.dims.length + j]! * scaled[j]!
    return s
  })
  const mx = Math.max(...scores)
  const exps = scores.map(x => Math.exp(x - mx))
  const sum = exps.reduce((a, b) => a + b, 0)
  const probs = exps.map(x => x / sum)
  let best = 0
  for (let i = 1; i < scores.length; i++) if (scores[i]! > scores[best]!) best = i
  return {scores, probs, best, bestName: W.channels[best]!}
}

// 提取一段文本中命中的症状中文词（按维度，最多每维3词）
export function extractSymptomWords(text: string): string[] {
  const joined = simplify(text)
  const words: string[] = []
  for (const d of Object.keys(DICT)) {
    let n = 0
    for (const w of DICT[d] ?? []) {
      let i = 0
      while ((i = joined.indexOf(w, i)) !== -1) { n++; i += w.length }
    }
    if (n > 0) words.push(DIM_ZH[d]!)
  }
  return words
}
